import collections, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
LP = "[lua:4rtefakt.solorando] "


def recheck(out):
    """Every layout the run printed ("place <char> <seed> <location index>=<item>"), re-checked here in Python
    against the same data: each item of the shuffled pool used once, and everything reachable from nothing."""
    layouts = collections.defaultdict(dict)
    for char, seed, i, item in re.findall(r"place (\w+) (\S+) (\d+)=(.+)", out):
        layouts[(char, seed)][int(i)] = item.strip()
    if not layouts:
        return "no layout printed"
    for (char, seed), placed in layouts.items():
        data = json.load(open(os.path.join(HERE, "..", "data", char + ".json"), encoding="utf-8"))
        slots = [i for i, l in enumerate(data["locs"]) if l["shuffle"]]
        if sorted(placed) != slots:
            return f"{char} {seed}: {len(placed)} chests placed, {len(slots)} expected"
        if sorted(placed.values()) != sorted(data["locs"][i]["item"] for i in slots):
            return f"{char} {seed}: the items placed are not the shuffled pool"
        names = [placed.get(i, l["item"]) for i, l in enumerate(data["locs"])]
        have, reach, got, grew = collections.Counter(data["start"]), {0}, set(), True

        def ok(r):
            if r is True or r is False:
                return r
            if r[0] == "has":
                return have[r[1]] >= r[2]
            if r[0] == "reach":
                return r[1] in reach
            return (all if r[0] == "all" else any)(ok(c) for c in r[1:])
        while grew:
            grew = False
            for a, b, r in data["entrances"]:
                if a in reach and b not in reach and ok(r):
                    reach.add(b)
                    grew = True
            for i, l in enumerate(data["locs"]):
                if i not in got and l["region"] in reach and ok(l["rule"]):
                    got.add(i)
                    grew = True
                    if names[i]:
                        have[names[i]] += 1
        if len(got) != len(data["locs"]) or data["goal"] not in reach:
            return f"{char} {seed}: NOT beatable ({len(got)}/{len(data['locs'])} locations)"
    moved = sum(1 for (char, seed), placed in layouts.items()
                for i, item in placed.items()
                if item != json.load(open(os.path.join(HERE, "..", "data", char + ".json"), encoding="utf-8"))["locs"][i]["item"])
    print(f"     re-checked {len(layouts)} layouts in Python: all beatable, {moved} chests changed in total")
    return None


def gens(seeds):
    cmds, t = [], 20
    for char in ("yunica", "hugo", "toal"):
        for s in seeds:
            cmds.append("%d:lua=solo gen %s %s" % (t, char, s))
            t += 30
    return ";".join(cmds) + ";%d:quit" % (t + 20)


